"""Shared test configuration.

- Network guard (NFR-2): any connection or DNS lookup to a non-loopback host fails the test.
- ``@pytest.mark.req("FR-1", ...)`` links tests to SPEC requirements;
  ``pytest --collect-only -q --traceability=docs/traceability.md`` regenerates the table.
"""

import json
import socket
from collections import defaultdict
from pathlib import Path
from typing import Any

import pytest

FIXTURES = Path(__file__).parent / "fixtures"
_LOOPBACK = {"127.0.0.1", "::1", "localhost"}


def load_fixture(relative: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((FIXTURES / relative).read_text())
    return data


# --- network guard -----------------------------------------------------------------------


class ExternalNetworkError(RuntimeError):
    """A test tried to reach a host outside the machine (NFR-2: CI must not call external APIs)."""


def _is_local(address: object) -> bool:
    if isinstance(address, tuple) and address:
        return str(address[0]) in _LOOPBACK
    return isinstance(address, str | bytes)  # AF_UNIX path


@pytest.fixture(autouse=True)
def _no_external_network(monkeypatch: pytest.MonkeyPatch) -> None:
    real_connect = socket.socket.connect
    real_connect_ex = socket.socket.connect_ex
    real_getaddrinfo = socket.getaddrinfo

    def guarded_connect(self: socket.socket, address: Any) -> None:
        if not _is_local(address):
            raise ExternalNetworkError(f"external connection attempted: {address!r}")
        real_connect(self, address)

    def guarded_connect_ex(self: socket.socket, address: Any) -> int:
        if not _is_local(address):
            raise ExternalNetworkError(f"external connection attempted: {address!r}")
        return real_connect_ex(self, address)

    def guarded_getaddrinfo(host: Any, *args: Any, **kwargs: Any) -> Any:
        if host is not None and str(host) not in _LOOPBACK:
            raise ExternalNetworkError(f"external DNS lookup attempted: {host!r}")
        return real_getaddrinfo(host, *args, **kwargs)

    monkeypatch.setattr(socket.socket, "connect", guarded_connect)
    monkeypatch.setattr(socket.socket, "connect_ex", guarded_connect_ex)
    monkeypatch.setattr(socket, "getaddrinfo", guarded_getaddrinfo)


# --- requirement traceability ------------------------------------------------------------


def pytest_addoption(parser: pytest.Parser) -> None:
    parser.addoption(
        "--traceability",
        metavar="PATH",
        default=None,
        # Use the `--traceability=PATH` form: with a space, pytest's early argument scan takes PATH
        # for a test path, looks for conftests next to it and never registers this option.
        help="write a requirement -> tests markdown table built from @pytest.mark.req markers",
    )


def pytest_collection_finish(session: pytest.Session) -> None:
    target = session.config.getoption("--traceability")
    if not target:
        return
    by_req: dict[str, list[str]] = defaultdict(list)
    for item in session.items:
        for marker in item.iter_markers(name="req"):
            for req in marker.args:
                by_req[str(req)].append(item.nodeid.split("[", 1)[0])  # one row per test function
    Path(target).write_text(render_traceability(by_req))


def _req_sort_key(req: str) -> tuple[str, int, str]:
    prefix, _, number = req.partition("-")
    return (prefix, int(number) if number.isdigit() else 0, req)


def render_traceability(by_req: dict[str, list[str]]) -> str:
    lines = [
        "# Traceability: requirements -> tests",
        "",
        "Generated by `uv run pytest --collect-only -q --traceability=docs/traceability.md`"
        " from `@pytest.mark.req(...)` markers. Do not edit by hand.",
        "",
        "| Requirement | Tests |",
        "|---|---|",
    ]
    for req in sorted(by_req, key=_req_sort_key):
        tests = "<br>".join(f"`{nodeid}`" for nodeid in sorted(set(by_req[req])))
        lines.append(f"| {req} | {tests} |")
    return "\n".join(lines) + "\n"
